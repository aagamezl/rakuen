local keycombo = require("rakuen.core.keycombo")

describe("keycombo", function()
  describe("normalize", function()
    it("lowercases and orders modifiers", function()
      assert.are.equal("ctrl+shift+tab", keycombo.normalize("Shift+Ctrl+Tab"))
    end)

    it("resolves modifier aliases", function()
      assert.are.equal("alt+tab", keycombo.normalize("Opt+Tab"))
      assert.are.equal("alt+tab", keycombo.normalize("Option+Tab"))
      assert.are.equal("cmd+space", keycombo.normalize("Super+Space"))
      assert.are.equal("cmd+space", keycombo.normalize("Command+Space"))
      assert.are.equal("ctrl+c", keycombo.normalize("Control+C"))
    end)

    it("resolves key aliases", function()
      assert.are.equal("cmd+`", keycombo.normalize("Cmd+grave"))
      assert.are.equal("pageup", keycombo.normalize("Page_Up"))
      assert.are.equal("ctrl+delete", keycombo.normalize("Ctrl+Backspace"))
    end)

    it("accepts a key with no modifiers", function()
      assert.are.equal("f2", keycombo.normalize("F2"))
    end)

    it("accepts + as the key", function()
      assert.are.equal("ctrl++", keycombo.normalize("Ctrl++"))
    end)

    it("is idempotent", function()
      local once = keycombo.normalize("Ctrl+Alt+Delete")
      assert.are.equal(once, keycombo.normalize(once))
    end)
  end)

  describe("parse", function()
    it("returns modifiers and key", function()
      local parsed = keycombo.parse("Cmd+Shift+Left")
      assert.are.same({ "cmd", "shift" }, parsed.modifiers)
      assert.are.equal("left", parsed.key)
    end)

    it("rejects an empty chord", function()
      assert.has_error(function()
        keycombo.parse("")
      end)
    end)

    it("rejects an unknown modifier", function()
      assert.has_error(function()
        keycombo.parse("Hyper+C")
      end)
    end)

    it("rejects a chord with only modifiers", function()
      assert.has_error(function()
        keycombo.parse("Ctrl+Shift")
      end)
    end)
  end)

  describe("from_event", function()
    it("builds the same chord as normalize", function()
      local chord = keycombo.from_event({ shift = true, ctrl = true }, "tab")
      assert.are.equal(keycombo.normalize("Ctrl+Shift+Tab"), chord)
    end)

    it("ignores the fn flag", function()
      assert.are.equal("ctrl+left", keycombo.from_event({ ctrl = true, fn = true }, "left"))
    end)
  end)
end)
